"""Count scenes, frames and labelled objects per {split, city, day/night, class}.

Uses the same label rules as training (`data.labels.frame_labels`), so the numbers are exactly the
objects the models will be trained and scored on. Only the metadata tables are read, no images.

    .venv/Scripts/python scripts/count_objects.py \
        --root dataset/v1.0-trainval --out docs/object_counts.md
"""

import argparse
from collections import defaultdict
from pathlib import Path

import numpy as np
from nuscenes.nuscenes import NuScenes

from sensor_fusion.data.labels import CLASS_NAMES, frame_labels
from sensor_fusion.data.splits import get_split_scenes, scene_is_night

DISTANCE_EDGES = (0.0, 20.0, 40.0, 60.0, float("inf"))  # metres, for the far-object count


def count(root: str, version: str, splits: tuple[str, ...]) -> dict[tuple[str, str, str], dict]:
    nusc = NuScenes(version, dataroot=root, verbose=False)
    log_location = {log["token"]: log["location"] for log in nusc.log}
    cells: dict[tuple[str, str, str], dict] = defaultdict(
        lambda: {
            "scenes": 0,
            "frames": 0,
            "classes": np.zeros(len(CLASS_NAMES), dtype=np.int64),
            "far": 0,  # objects 40 m or farther
            "objects": 0,
        }
    )
    for split in splits:
        wanted = set(get_split_scenes(split))
        for scene in nusc.scene:
            if scene["name"] not in wanted:
                continue
            city = log_location[scene["log_token"]].split("-")[0]
            key = (split, city, "night" if scene_is_night(scene) else "day")
            cell = cells[key]
            cell["scenes"] += 1
            token = scene["first_sample_token"]
            while token:
                sample = nusc.get("sample", token)
                _, classes, distances = frame_labels(nusc, sample["data"]["CAM_FRONT"])
                cell["frames"] += 1
                cell["objects"] += len(classes)
                cell["classes"] += np.bincount(classes, minlength=len(CLASS_NAMES))
                cell["far"] += int((distances >= DISTANCE_EDGES[2]).sum())
                token = sample["next"]
    return cells


def to_markdown(cells: dict[tuple[str, str, str], dict]) -> str:
    header = ["split", "city", "time", "scenes", "frames", "objects", *CLASS_NAMES, "objects>=40m"]
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for (split, city, tod), cell in sorted(cells.items()):
        row = [
            split,
            city,
            tod,
            cell["scenes"],
            f"{cell['frames']:,}",
            f"{cell['objects']:,}",
            *(f"{n:,}" for n in cell["classes"]),
            f"{cell['far']:,}",
        ]
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default="dataset/v1.0-trainval")
    parser.add_argument("--version", default="v1.0-trainval")
    parser.add_argument("--splits", nargs="+", default=["train", "val"])
    parser.add_argument("--out", default=None, help="also write the table to this markdown file")
    args = parser.parse_args()

    table = to_markdown(count(args.root, args.version, tuple(args.splits)))
    print(table)
    if args.out:
        Path(args.out).write_text(
            "# Objects per split, city and time of day\n\n"
            f"Generated by `scripts/count_objects.py` on `{args.version}` with the training label "
            "rules (4 merged classes, visibility >= 40%, front camera).\n\n" + table + "\n",
            encoding="utf-8",
        )


if __name__ == "__main__":
    main()
